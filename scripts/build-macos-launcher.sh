#!/bin/bash
# Build a genuine native AppKit application; ships a fixed allowlist of JS runtime files.
# Run on macOS with Xcode Command Line Tools / swiftc and Node 22+.
set -euo pipefail

if [[ "$(uname -s)" != "Darwin" ]]; then
  echo '仅支持在 macOS 上构建原生 .app（需要 macOS AppKit SDK）。' >&2
  exit 1
fi
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
command -v swiftc >/dev/null || { echo '请先安装 Xcode Command Line Tools：xcode-select --install' >&2; exit 1; }
command -v node >/dev/null || { echo 'Node.js 22+ 未安装。' >&2; exit 1; }
NODE_BIN="$(command -v node)"
NODE_VERSION="$(node -p 'process.versions.node.split(".")[0]')"
if (( NODE_VERSION < 22 )); then echo '需要 Node.js 22+' >&2; exit 1; fi

DEST="$ROOT/dist/Codex Usage Launcher.app"
# Remove only the exact application bundle generated by this build script.
if [[ -e "$DEST" ]]; then
  PLIST="$DEST/Contents/Info.plist"
  if [[ ! -f "$PLIST" ]] || [[ "$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$PLIST" 2>/dev/null || true)" != 'dev.paperauk.codex-sidebar-usage.launcher' ]]; then
    echo "不覆盖未知的 .app：$DEST" >&2
    exit 1
  fi
  rm -rf -- "$DEST"
fi

mkdir -p "$DEST/Contents/MacOS" "$DEST/Contents/Resources/runtime/src" "$DEST/Contents/Resources/runtime/scripts"
cp "$ROOT/macos/Info.plist" "$DEST/Contents/Info.plist"
cp "$ROOT/src/sidebar.js" "$ROOT/src/app-server.mjs" "$ROOT/src/rate-limits.mjs" "$ROOT/src/monitor-utils.mjs" "$DEST/Contents/Resources/runtime/src/"
cp "$ROOT/scripts/run.mjs" "$ROOT/scripts/launch.mjs" "$DEST/Contents/Resources/runtime/scripts/"
cp "$ROOT/package.json" "$DEST/Contents/Resources/runtime/package.json"

/usr/bin/plutil -insert CSUNodePath -string "$NODE_BIN" "$DEST/Contents/Info.plist"
# Finder/Dock do not inherit the interactive shell PATH. Remember a verified
# Codex CLI from this terminal at build time, without copying CLI credentials.
CODEX_BIN="$(command -v codex || true)"
if [[ "$CODEX_BIN" == /* && -f "$CODEX_BIN" && -x "$CODEX_BIN" ]]; then
  /usr/bin/plutil -insert CSUCodexPath -string "$CODEX_BIN" "$DEST/Contents/Info.plist"
  printf '检测到 Codex CLI：%s\n' "$CODEX_BIN"
else
  printf '未检测到终端 Codex CLI；Launcher 将自动查找或允许手动选择。\n'
fi
swiftc -O -framework AppKit "$ROOT/macos/Launcher.swift" -o "$DEST/Contents/MacOS/CodexUsageLauncher"
chmod 755 "$DEST/Contents/MacOS/CodexUsageLauncher"
# Local ad hoc signature, no developer account, notarization or distribution claim.
if command -v codesign >/dev/null; then codesign --force --deep --sign - "$DEST" >/dev/null; fi
printf '已构建：%s\n使用 Node：%s\n' "$DEST" "$NODE_BIN"
printf '测试：open "%s"\n' "$DEST"
